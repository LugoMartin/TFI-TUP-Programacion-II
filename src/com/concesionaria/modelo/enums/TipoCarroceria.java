package com.concesionaria.modelo.enums;

/**
 * Tipos de carroceria admitidos para automoviles y camionetas.
 *
 * @author Desarrollo TFI - Programacion II
 * @version 1.0
 */
public enum TipoCarroceria {

    /** Automovil de tres volumenes con maletero separado. */
    SEDAN,

    /** Automovil compacto de dos volumenes. */
    HATCHBACK,

    /** Vehiculo de alto despeje y tamaño mediano o grande. */
    SUV,

    /** Camioneta con caja de carga abierta. */
    PICKUP,

    /** Vehiculo utilitario de carga o transporte de personas. */
    UTILITARIO
}
