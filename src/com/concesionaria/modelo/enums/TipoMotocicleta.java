package com.concesionaria.modelo.enums;

/**
 * Tipos de motocicleta admitidos en el stock de la concesionaria.
 *
 * @author Desarrollo TFI - Programacion II
 * @version 1.0
 */
public enum TipoMotocicleta {

    /** Motocicleta sin carenado, de uso urbano. */
    NAKED,

    /** Motocicleta de alto rendimiento y carenado deportivo. */
    DEPORTIVA,

    /** Motocicleta apta para caminos mixtos y tierra. */
    ENDURO,

    /** Motocicleta de pequeña cilindrada con transmision automatica. */
    SCOOTER,

    /** Motocicleta de estilo clasico y posicion de conduccion erguida. */
    CUSTOM
}
